#!/usr/bin/env node
/**
 * Generates THIRD-PARTY-NOTICES.txt from the production dependency tree.
 *
 * Enumerates every package that ships inside the packaged app (npm ls
 * --omit=dev --all), and concatenates each package's license text. Packages
 * whose install dir has no license file fall back to their declared SPDX id
 * and repository URL.
 *
 * Vendored assets — things that ship in the app but were never installed by
 * npm, so `npm ls` cannot see them — are declared in VENDORED below.
 *
 * Run after dependency changes: npm run licenses:generate
 */
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const OUT = path.join(root, "THIRD-PARTY-NOTICES.txt");

const LICENSE_FILES = /^(licen[sc]e|copying|notice)(\.(md|txt|markdown))?$/i;

/**
 * Files that ship inside the app without ever passing through npm, so the
 * dependency walk below cannot find them. Each entry points at the directory
 * holding the asset; the license text is read from that same directory by
 * `findLicenseText`, which keeps the licence beside the thing it covers (the
 * OFL requires the two travel together) instead of pasting it into this file.
 */
const VENDORED = [
  {
    key: "Inter@4.001",
    license: "OFL-1.1",
    repository: "https://github.com/rsms/inter",
    dir: path.join(root, "src", "renderer", "public", "fonts"),
  },
];

function findLicenseText(dir) {
  let entries;
  try {
    entries = fs.readdirSync(dir);
  } catch {
    return null;
  }
  const match = entries.find((f) => LICENSE_FILES.test(f));
  if (!match) return null;
  try {
    return fs.readFileSync(path.join(dir, match), "utf8").trim();
  } catch {
    return null;
  }
}

const raw = execSync("npm ls --omit=dev --all --parseable", {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});

const dirs = [...new Set(raw.split("\n").filter(Boolean))]
  .filter((d) => d !== root)
  .sort();

const packages = [];
const seen = new Set();
for (const dir of dirs) {
  let pkg;
  try {
    pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  } catch {
    continue;
  }
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) continue;
  seen.add(key);

  const license =
    typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? "Unknown";
  const repository =
    typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url ?? "";
  packages.push({ key, license, repository, text: findLicenseText(dir) });
}

const npmCount = packages.length;

// A vendored asset with no license text is a compliance hole, not a formatting
// problem, so it fails the build instead of falling through to the "see the
// repository" placeholder the npm branch uses.
for (const asset of VENDORED) {
  const text = findLicenseText(asset.dir);
  if (!text) {
    throw new Error(
      `No license file in ${path.relative(root, asset.dir)} for vendored asset ` +
        `${asset.key}. Restore it rather than shipping the asset unattributed.`,
    );
  }
  packages.push({ ...asset, text });
}

packages.sort((a, b) => a.key.localeCompare(b.key));

//const missing = packages.filter((p) => !p.text);
const divider = "=".repeat(72);

const header = `THIRD-PARTY SOFTWARE NOTICES AND INFORMATION

Mains bundles the third-party packages and assets listed below. Each is the
property of its respective authors and is licensed under its own terms,
reproduced here. This file is generated by scripts/generate-third-party-notices.mjs;
do not edit by hand.

Note on bundled proprietary components: the GitHub Copilot CLI
(@github/copilot, @github/copilot-darwin-*) and the Anthropic Claude Agent
SDK (@anthropic-ai/claude-agent-sdk, including its vendor directory) are NOT
open-source software. They are redistributed, unmodified, as part of this
application under the redistribution terms of their respective licenses,
which are reproduced in their sections below.

Packages: ${npmCount}
Bundled assets: ${VENDORED.length} (${VENDORED.map((v) => v.key).join(", ")})
`;

const body = packages
  .map((p) => {
    const lines = [divider, p.key, `License: ${p.license}`];
    if (p.repository) lines.push(`Repository: ${p.repository}`);
    lines.push(divider, "");
    lines.push(
      p.text ??
        `(No license file shipped in the package; see the repository above for the full ${p.license} text.)`,
    );
    return lines.join("\n");
  })
  .join("\n\n");

fs.writeFileSync(OUT, `${header}\n${body}\n`);

