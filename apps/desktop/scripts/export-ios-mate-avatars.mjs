import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const app = new URL("../", import.meta.url);
const output = new URL("../ios/Resources/RobotAvatars/", app);
const contractsSource = fileURLToPath(new URL("../../packages/contracts/src/", app));
const check = process.argv.includes("--check");
const result = await build({
  configFile: false,
  logLevel: "error",
  resolve: { alias: [{ find: /^@mains\/contracts\/(.+)$/, replacement: `${contractsSource}$1.ts` }] },
  build: {
    write: false,
    minify: true,
    lib: {
      entry: fileURLToPath(new URL("src/renderer/features/assistants/lib/assistant-robot-bundle.ts", app)),
      formats: ["iife"],
      name: "MainsRobot",
    },
  },
});
const bundle = (Array.isArray(result) ? result[0] : result).output.find(item => item.type === "chunk");
if (!bundle || bundle.imports.length || bundle.dynamicImports.length) throw new Error("Expected a self-contained avatar renderer");

const { catalogue } = new Function(`${bundle.code}\nreturn MainsRobot;`)();
await Promise.all(catalogue.styles.flatMap(style => style.presets.map(preset =>
  readFile(new URL(`src/renderer/features/assistants/assets/robots/${preset.id}.webp`, app)),
)));

for (const [name, contents] of [
  ["renderer.js", `// Generated by apps/desktop/scripts/export-ios-mate-avatars.mjs\n${bundle.code.trimEnd()}\n`],
  ["presets.json", JSON.stringify(catalogue, null, 2) + "\n"],
]) {
  const file = new URL(name, output);
  if (check) {
    if (await readFile(file, "utf8") !== contents) throw new Error(`${name} is out of date. Run node scripts/export-ios-mate-avatars.mjs from apps/desktop.`);
  } else await writeFile(file, contents);
}
