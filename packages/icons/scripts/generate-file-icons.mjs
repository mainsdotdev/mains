#!/usr/bin/env node
/** Export the desktop file icons and matching rules as platform-neutral SVG data. */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const icons = path.resolve(here, "../../../apps/desktop/src/renderer/components/ui/icons");
const read = (file) => readFileSync(file, "utf8");
const resolver = read(path.join(icons, "file-icon.tsx"));
const attributeName = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const escapeXml = (value) => value.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");

function componentSource(file) {
  const source = read(file);
  const reexport = source.match(/^export \{ default \} from "([^"]+)"/);
  return reexport ? read(path.resolve(path.dirname(file), `${reexport[1]}.tsx`)) : source;
}

function svgXml(source, name) {
  let svg = source.match(/<svg\b[\s\S]*?<\/svg>/)?.[0];
  if (!svg) throw new Error(`Missing SVG for ${name}`);
  const classes = new Map();
  svg = svg.replace(/<style>\{("(?:[^"\\]|\\.)*")\}<\/style>/g, (_, value) => {
    const css = JSON.parse(value);
    for (const [, name, rules] of css.matchAll(/\.([\w-]+)\{([^}]+)\}/g)) {
      classes.set(name, rules.split(";").filter(Boolean).map((rule) => {
        const [key, value] = rule.split(":");
        return `${key}="${escapeXml(value)}"`;
      }).join(" "));
    }
    return "";
  });
  svg = svg
    .replace(/\s*\{\.\.\.props\}/g, "")
    .replace(/<title>[\s\S]*?<\/title>/g, "")
    .replace(/className="([^"]+)"/g, (_, className) => {
      if (!classes.has(className)) throw new Error(`Unknown class ${className} in ${name}`);
      return classes.get(className);
    })
    .replace(/style=\{\{([\s\S]*?)\}\}/g, (_, fields) => {
      const values = [...fields.matchAll(/(\w+):\s*("[^"]*"|[-\d.]+),?/g)];
      if (fields.replace(/(\w+):\s*("[^"]*"|[-\d.]+),?/g, "").trim()) throw new Error(`Unsupported style in ${name}`);
      return values.map(([, key, value]) => `${attributeName(key)}="${escapeXml(String(JSON.parse(value)))}"`).join(" ");
    })
    .replace(/(\w+)=\{(-?[\d.]+)\}/g, '$1="$2"')
    .replace(/\{("(?:[^"\\]|\\.)*")\}/g, (_, value) => escapeXml(JSON.parse(value)))
    .replace(/\b((?:fill|clip|font|stop|stroke|text)[A-Z]\w*)=/g, (_, name) => `${attributeName(name)}=`)
    .replace(/\s+/g, " ").replace(/>\s+</g, "><").trim();
  if (/[{}]/.test(svg)) throw new Error(`Unsupported JSX in ${name}`);
  return svg;
}

const lines = [
  "// Generated by packages/icons/scripts/generate-file-icons.mjs from the desktop",
  "// file-icon.tsx and file-icons/*.tsx. Do not edit by hand.",
  "",
];
for (const [, name, relative] of read(path.join(icons, "file-icons/index.tsx")).matchAll(/export \{ default as (\w+) \} from "([^"]+)"/g)) {
  const svg = svgXml(componentSource(path.join(icons, "file-icons", `${relative}.tsx`)), name);
  lines.push(`const ${name} = ${JSON.stringify(svg)};`);
}
for (const name of ["EXTENSION_ICONS", "FILENAME_ICONS"]) {
  const body = resolver.match(new RegExp(`const ${name}: Record<string, FileIconType> = \\{([\\s\\S]*?)\\n\\};`))?.[1];
  if (!body) throw new Error(`Missing ${name}`);
  lines.push("", `export const ${name}: Record<string, string> = {${body}\n};`);
}
const patterns = resolver.match(/const CONFIG = [\s\S]*?\n\];/)?.[0];
if (!patterns) throw new Error("Missing filename patterns");
lines.push("", patterns.replace("const FILENAME_PATTERNS:", "export const FILENAME_PATTERNS:").replace("[RegExp, FileIconType]", "[RegExp, string]"), "");
writeFileSync(path.resolve(here, "../src/file-icons.generated.ts"), lines.join("\n"));
console.log("Generated desktop file icons and matching rules.");
